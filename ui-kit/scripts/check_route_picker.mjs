assert.match(legacy, /MTP depth/);
assert.match(legacy, /Workflow \/ Gateway default/);

// inheritLabel replaces the inherit choice in both selects.
const entityCustom = renderToStaticMarkup(h(ProviderModelPicker, {
  ...base, inheritLabel: "Gateway default", optionsInDefaultMode: false,
  value: { provider: "lmstudio", model: "m", reasoning: "low" },
}));
assert.match(entityCustom, /MTP depth/);
assert.match(entityCustom, /Reasoning effort/);
assert.doesNotMatch(entityCustom, /Workflow \/ Gateway default/);

// optionsInDefaultMode: false hides reasoning + MTP while on the gateway default.
const entityDefault = renderToStaticMarkup(h(ProviderModelPicker, {
  ...base, inheritLabel: "Gateway default", optionsInDefaultMode: false,
  defaultHint: "Gateway default: lmstudio · route-model.",
  value: { provider: "", model: "", reasoning: "low" },
}));
assert.doesNotMatch(entityDefault, /MTP depth/);
assert.doesNotMatch(entityDefault, /Reasoning effort/);
assert.match(entityDefault, /Gateway default: lmstudio · route-model\./);
