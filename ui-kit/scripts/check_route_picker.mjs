const h = React.createElement;
let routeFailures = 0;
function check(name, cond, detail) {
  if (cond) return;
  routeFailures += 1;
  console.error(`  FAIL ${name}${detail ? ` — ${detail}` : ""}`);
}
const none = async () => [];
const base = {
  onChange: () => {},
  fetchProviders: none,
  fetchModels: none,
  fetchModelCapabilities: async () => ({}),
  enableSpeculation: true,
};

// Defaults unchanged: on Gateway default the MTP select shows with the
// workflow-aware inherit label (Code / Assistant behaviour).
