/**
 * The replay view client (`replay_view_v1`, AbstractRuntime `abstractruntime.replay`, served by
 * AbstractGateway >= 0.17.0):
 *
 *   GET  runs/{run_id}/view          the whole view; ETag = its cursor token; 304 on If-None-Match
 *   GET  runs/{run_id}/view/stream   SSE: one `view` (id = token), then `delta` frames
 *                                    (id = token), `: keep-alive` comments, `done` at the end;
 *                                    reconnect with `Last-Event-ID`
 *
 * The view is the ONE reconstruction of a run tree (root backlog 0993, runtime ADR 0010): status,
 * the person-facing interaction with its resume `command`, messages, activities, artifacts,
 * usage. A client folds the stream with `applyDelta` and renders the result; it never re-derives
 * run state from raw ledger records.
 *
 * `applyDelta` is a port of `abstractruntime.replay.delta.apply_delta` (0.15.0). It is checked
 * against the gateway itself: `scripts/check_replay_view.mjs` folds every conformance case's
 * captured stream and requires the folded view to serialize to the bytes of the gateway's
 * `GET /view` after EVERY record (fixtures: `scripts/fixtures/replay_view/`, regenerated by
 * `scripts/regen_replay_view_fixtures.py` against a real gateway).
 */

