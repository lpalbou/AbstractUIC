export const REPLAY_VIEW_VERSION = "replay_view_v1";
export const REPLAY_SCALAR_KEYS = ["version", "root_run_id", "workflow", "session_id", "status", "display_status", "cursor", "interaction", "open_waits", "usage", "warnings"] as const;
export const REPLAY_LIST_KEYS = ["runs", "messages", "activities", "artifacts"] as const;

type Row = Record<string, unknown>;
const own = (value: object, key: string): boolean => Object.prototype.hasOwnProperty.call(value, key);

/** Python's `str()` of a JSON scalar (the reducer's sort and id keys are built with it). */
function pyStr(value: unknown): string {
  if (value === null || value === undefined) return "None";
  if (value === true) return "True";
  if (value === false) return "False";
  return String(value);
}

/** `f"{x:012d}"` for an int (bool included, as `isinstance(True, int)`), else `str(x)`. */
function orderPart(value: unknown): string {
  const n = typeof value === "boolean" ? Number(value) : value;
  if (typeof n === "number" && Number.isInteger(n)) {
    const digits = String(Math.abs(n));
    return n < 0 ? `-${digits.padStart(11, "0")}` : digits.padStart(12, "0");
  }
  return pyStr(value);
}

/** Python string order (by code point), not UTF-16 code units. */
function comparePy(a: string, b: string): number {
  if (a === b) return 0;
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i += 1) {
    const x = a.charCodeAt(i);
    const y = b.charCodeAt(i);
    if (x === y) continue;
    const surrogate = (c: number) => c >= 0xd800 && c <= 0xdfff;
    if (surrogate(x) || surrogate(y)) return (a.codePointAt(i) ?? x) - (b.codePointAt(i) ?? y);
    return x - y;
  }
  return a.length - b.length;
}

function itemId(key: string, item: Row): string {
  return pyStr(key === "runs" ? item.run_id : item.id);
}

function orderKey(key: string, item: Row): [string[], string] {
  const order = Array.isArray(item.order) && item.order.length ? item.order : [];
  return [order.map(orderPart), itemId(key, item)];
}

function compareKeys(a: [string[], string], b: [string[], string]): number {
  const n = Math.min(a[0].length, b[0].length);
  for (let i = 0; i < n; i += 1) {
    const c = comparePy(a[0][i], b[0][i]);
    if (c) return c;
  }
  if (a[0].length !== b[0].length) return a[0].length - b[0].length;
  return comparePy(a[1], b[1]);
}

/** The view's own item order (`order` element by element, then `id`), for merging its lists. */
export function compareReplayOrder(a: { order?: unknown[] | null; id?: unknown }, b: { order?: unknown[] | null; id?: unknown }): number {
  return compareKeys(orderKey("messages", a as Row), orderKey("messages", b as Row));
}

function jsonEqual(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (a === undefined || b === undefined) return a === b || (a == null && b == null);
  if (Array.isArray(a) || Array.isArray(b)) {
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
    return a.every((x, i) => jsonEqual(x, b[i]));
  }
  if (a && b && typeof a === "object" && typeof b === "object") {
    const ka = Object.keys(a as Row);
    const kb = Object.keys(b as Row);
    return ka.length === kb.length && ka.every((k) => own(b as Row, k) && jsonEqual((a as Row)[k], (b as Row)[k]));
  }
  return false;
}

/**
 * `view` with `delta` applied (neither argument is modified): the scalars present in the delta
 * replace the view's, the delta's list items are upserted by id (`run_id` for runs) and a list
 * is re-sorted by `order` (element by element, ints zero-padded, then id) when an item is new
 * or moved. Items are never removed. `changes` is ignored. Port of AbstractRuntime 0.15.0
 * `replay.delta.apply_delta`; the result shares unchanged items with `view` (treat views as
 * immutable).
 */
export function applyDelta<V extends Row = ReplayView & Row>(view: V | Row | null | undefined, delta: Row): V {
  const out: Row = view && Object.keys(view).length ? { ...view } : Object.fromEntries(REPLAY_LIST_KEYS.map((k) => [k, []]));
  for (const k of REPLAY_SCALAR_KEYS) if (own(delta, k)) out[k] = delta[k];
  for (const k of REPLAY_LIST_KEYS) {
    const items = delta[k];
    const current = Array.isArray(out[k]) && (out[k] as unknown[]).length ? (out[k] as Row[]) : [];
    if (!Array.isArray(items) || !items.length) {
      out[k] = current;
      continue;
    }
    const rows = [...current];
    const where = new Map<string, number>(rows.map((it, i) => [itemId(k, it), i]));
    let resort = false;
    for (const raw of items as Row[]) {
      const id = itemId(k, raw);
      const i = where.get(id);
      if (i === undefined) {
        where.set(id, rows.length);
        rows.push(raw);
        resort = true;
      } else {
        if (!jsonEqual(rows[i].order ?? null, raw.order ?? null)) resort = true;
        rows[i] = raw;
      }
    }
    if (resort) {
      const keyed = rows.map((it) => ({ it, key: orderKey(k, it) }));
      keyed.sort((a, b) => compareKeys(a.key, b.key));
      out[k] = keyed.map((x) => x.it);
    } else out[k] = rows;
  }
  return out as V;
}

/** `"<run id prefix>:<seq>.…[~digest]"` (a view's `cursor.token`, ETag, SSE id) -> {prefix: seq}; null when not one. */
export function parseCursorToken(token: unknown): Record<string, number> | null {
  if (typeof token !== "string" || !token.trim()) return null;
  let raw = token.trim();
  if (raw.startsWith("W/")) raw = raw.slice(2);
  raw = raw.replace(/^"+|"+$/g, "");
  const out: Record<string, number> = {};
  for (const part of raw.split("~", 1)[0].split(".")) {
    const at = part.indexOf(":");
    if (at < 0) return null;
    const prefix = part.slice(0, at).trim();
    const seqText = part.slice(at + 1).trim();
    if (!prefix || !/^[+-]?\d+$/.test(seqText)) return null;
    const n = Number(seqText);
    if (n < 0) return null;
    out[prefix] = n;
  }
  return Object.keys(out).length ? out : null;
}

// ---------------------------------------------------------------------------------------- SSE

/** One server-sent event: `event` (default "message"), `data` (lines joined by "\n"), `id` when the frame had one. */
export type SseFrame = { event: string; data: string; id?: string };

/**
 * An incremental `text/event-stream` parser (WHATWG rules: CRLF/LF/CR lines, `:` comments,
 * multi-line `data`, one leading space stripped, a frame without data is not dispatched).
 * `lastEventId` is the stream's last `id:` (what a reconnect sends as `Last-Event-ID`).
 */
export class SseParser {
  lastEventId = "";
  private buffer = "";
  private event = "";
  private data: string[] = [];
  private id: string | undefined;
  private pendingCr = false;

  push(chunk: string): SseFrame[] {
    const frames: SseFrame[] = [];
    let text = chunk;
    if (this.pendingCr && text.startsWith("\n")) text = text.slice(1);
    this.pendingCr = false;
    this.buffer += text;
    for (;;) {
      const m = /\r\n|\n|\r/.exec(this.buffer);
      if (!m) break;
      // A trailing CR may be the first half of CRLF: wait for the next chunk.
      if (m[0] === "\r" && m.index === this.buffer.length - 1) {
        const line = this.buffer.slice(0, m.index);
        this.buffer = "";
        this.pendingCr = true;
        this.line(line, frames);
        break;
      }
      const line = this.buffer.slice(0, m.index);
      this.buffer = this.buffer.slice(m.index + m[0].length);
      this.line(line, frames);
    }
    return frames;
  }

  private line(line: string, frames: SseFrame[]): void {
    if (line === "") {
      if (this.data.length) frames.push({ event: this.event || "message", data: this.data.join("\n"), ...(this.id !== undefined ? { id: this.id } : {}) });
      this.event = "";
      this.data = [];
      this.id = undefined;
      return;
    }
    if (line.startsWith(":")) return;
    const at = line.indexOf(":");
    const field = at < 0 ? line : line.slice(0, at);
    let value = at < 0 ? "" : line.slice(at + 1);
    if (value.startsWith(" ")) value = value.slice(1);
    if (field === "event") this.event = value;
    else if (field === "data") this.data.push(value);
    else if (field === "id" && !value.includes("\u0000")) {
      this.id = value;
      this.lastEventId = value;
    }
  }
}

// ---------------------------------------------------------------------------------------- fold

/** What folding one frame did. `duplicate`/`stale`: the frame was older than the held view and was NOT applied. */
export type ReplayFoldOutcome = "view" | "delta" | "duplicate" | "stale" | "done" | "ignored";

/**
 * The client's copy of one view, folded from stream frames. A `view` frame replaces it; a
 * `delta` is applied unless it is the frame already applied (same id) or older than the held
 * cursor (every run's seq at or below the held one, one below): a frame delivered again after
 * a reconnect never moves the view back. A delta before any view throws (reconnect without
 * `Last-Event-ID`).
 */
export class ReplayViewFold {
  view: ReplayView | null = null;
  lastEventId: string | null = null;
  terminal = false;

  /**
   * Start from (or replace with) a view read with `GET /view` (its ETag/`cursor.token` is the
   * stream's `Last-Event-ID`). A read older than the held view (a slow GET overtaken by stream
   * frames) is refused: returns false and keeps the newer view.
   */
  adopt(view: ReplayView, etag?: string | null): boolean {
    if (this.view && isOlderCursor(view.cursor?.runs, this.view.cursor?.runs)) return false;
    this.view = view;
    this.lastEventId = unquoteEtag(etag) || view.cursor?.token || null;
    return true;
  }

  apply(frame: SseFrame): ReplayFoldOutcome {
    if (frame.event === "done") { this.terminal = true; return "done"; }
    if (frame.event !== "view" && frame.event !== "delta") return "ignored";
    const data = JSON.parse(frame.data) as Row;
    if (frame.event === "view") {
      this.view = data as unknown as ReplayView;
      this.lastEventId = frame.id || this.view.cursor?.token || null;
      return "view";
    }
    if (!this.view) throw new Error("replay view: a delta arrived before any view (reconnect without Last-Event-ID).");
    const id = frame.id || (data.cursor as ReplayViewCursor | undefined)?.token || null;
    if (id && id === this.lastEventId) return "duplicate";
    if (isOlderCursor((data.cursor as ReplayViewCursor | undefined)?.runs, this.view.cursor?.runs)) return "stale";
    this.view = applyDelta<ReplayView & Row>(this.view as ReplayView & Row, data);
    this.lastEventId = id;
    return "delta";
  }
}

function unquoteEtag(etag: string | null | undefined): string {
  const raw = String(etag || "").trim().replace(/^W\//, "");
  return raw.replace(/^"|"$/g, "");
}

/** True when `incoming` is behind `held`: no run ahead, at least one run behind. */
function isOlderCursor(incoming: Record<string, number> | undefined, held: Record<string, number> | undefined): boolean {
  if (!incoming || !held) return false;
  let behind = false;
  for (const [run, seq] of Object.entries(held)) {
    const next = incoming[run];
    // A run the incoming frame does not know yet (a child linked since): that frame is older.
    if (typeof next !== "number") { if (seq > 0) behind = true; continue; }
    if (next > seq) return false;
    if (next < seq) behind = true;
  }
  for (const [run, seq] of Object.entries(incoming)) if (!(run in held) && seq > 0) return false;
  return behind;
}

