import assert from "node:assert/strict";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { ChatComposer } from "../dist/chat_composer.js";
import { WorkflowChat } from "../dist/workflow_chat.js";
const base = { value: "Two lines\nKept here", onChange() {}, onSubmit() {}, actions: React.createElement("button", { "aria-label": "Microphone" }, "Mic"), leading: React.createElement("span", null, "example.txt") };
const normal = renderToStaticMarkup(React.createElement(ChatComposer, base));
assert(normal.includes('rows="3"'));
assert(normal.includes('class="pc-composer"'));
assert(!normal.includes("pc-composer--compact"));
assert(normal.includes(">Send</button>"));
const compact = renderToStaticMarkup(React.createElement(ChatComposer, { ...base, variant: "compact", sendLabel: "Reply" }));
assert(compact.includes('rows="2"'));
assert(compact.includes("pc-composer--compact"));
assert(compact.includes('aria-label="Reply"'));
assert(compact.includes("example.txt") && compact.includes('aria-label="Microphone"'));
assert(compact.includes("pc-composer__send--compact"));
const waiting = renderToStaticMarkup(React.createElement(ChatComposer, { ...base, variant: "compact", busy: true, busyLabel: "Sending correction…" }));
assert(waiting.includes('aria-label="Sending correction…"') && waiting.includes('aria-busy="true"') && waiting.includes('disabled=""'));
const chat = renderToStaticMarkup(React.createElement(WorkflowChat, { messages: [], draft: "Kept draft", onDraftChange() {}, onSend() {}, composerVariant: "compact", onAttach() {}, composerExtras: React.createElement("button", null, "Voice") }));
assert(chat.includes("pc-composer--compact") && chat.includes('aria-label="Attach file"') && chat.includes("Voice") && chat.includes("Kept draft"));
console.log("compact composer: optional API, default markup, multiline minimum, accessible send states and existing slots passed");
